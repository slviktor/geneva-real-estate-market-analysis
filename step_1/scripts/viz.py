def qoq_badge(pct: float) -> tuple[str, str, str]:
    if abs(pct) < 0.05:
        return f"{pct:.1f}% QoQ", "#57534E", "#E7E5E4"
    if pct > 0:
        return f"▲ +{pct:.1f}% QoQ", "#166534", "#DCFCE7"
    return f"▼ {pct:.1f}% QoQ", "#B91C1C", "#FEE2E2"


