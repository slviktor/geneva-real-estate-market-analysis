def avg_ticket_quarter(vol: pd.DataFrame, year: int, quarter: int) -> pd.DataFrame:
    order = ["house_existing", "house_new", "ppe_existing", "ppe_new"]
    df = vol[
        (vol.source == "T_05_05_1_1_01")
        & (vol.freq == "Q")
        & (vol.year == year)
        & (vol.quarter == quarter)
        & (vol.type_id.isin(order))
    ][["type_id", "n", "value_chf"]].copy()
    df["avg_chf"] = df["value_chf"] / df["n"]
    return df.set_index("type_id").loc[order].reset_index()


def latest_quarter(price: pd.DataFrame, vol: pd.DataFrame) -> tuple[int, int]:
    q_price = price[
        (price.source == "T_05_05_1_1_02")
        & (price.freq == "Q")
        & (price["median"].notna())
        & (price.type_id.isin(["house_existing", "ppe_existing"]))
    ][["year", "quarter"]].drop_duplicates()
    q_vol = vol[
        (vol.source == "T_05_05_1_1_01")
        & (vol.freq == "Q")
        & (vol["n"].notna())
        & (vol["value_chf"].notna())
        & (vol.type_id.isin(["house_existing", "house_new", "ppe_existing", "ppe_new"]))
    ][["year", "quarter"]].drop_duplicates()
    q = q_price.merge(q_vol, on=["year", "quarter"])
    last = q.sort_values(["year", "quarter"]).iloc[-1]
    return int(last["year"]), int(last["quarter"])


def prev_quarter(year: int, quarter: int) -> tuple[int, int]:
    return (year - 1, 4) if quarter == 1 else (year, quarter - 1)


