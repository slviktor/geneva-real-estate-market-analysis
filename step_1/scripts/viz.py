def _commune_range_chart(
    df_cur: pd.DataFrame,
    df_prev: pd.DataFrame | None,
    canton_med: float,
    c: dict,
    bar_color: str,
) -> plt.Figure:
    """Shared renderer for commune-level P25-P75 charts (04 and 04b)."""
    df = df_cur.sort_values("median").reset_index(drop=True)
    if df_prev is not None and len(df_prev):
        prev = df_prev[["geo_label", "median"]].rename(columns={"median": "med_prev"})
        df = df.merge(prev, on="geo_label", how="left")
    else:
        df["med_prev"] = pd.NA

    n_items = len(df)
    fig, ax = plt.subplots(figsize=(9.0, max(5.8, 0.52 * n_items + 2.0)))

    ax.axvline(canton_med, color=bar_color, linestyle="--",
               linewidth=1.2, alpha=0.5, zorder=1)
    ax.text(canton_med, -0.50,
            f"{c['vline_label']}  {fmt_int(canton_med)} CHF/m²",
            ha="center", va="top", fontsize=9, color=bar_color, style="italic")

    for i, row in df.iterrows():
        lo, mid, hi = row["p25"], row["median"], row["p75"]
        n = int(row["n"])
        label = f"{row['geo_label']}  (n={n})"
        ax.plot([lo, hi], [i, i], color=bar_color, linewidth=8,
                solid_capstyle="round", alpha=0.85)
        ax.scatter(mid, i, s=70, color="#FBBF24",
                   edgecolors="white", linewidths=1.0, zorder=4)
        ax.text(hi + 80, i + 0.05, f"{fmt_int(mid)}",
                va="center", fontsize=9, color=INK, fontweight="bold")

        if pd.notna(row.get("med_prev")):
            pct = (mid / row["med_prev"] - 1) * 100
            if abs(pct) < 0.05:
                btxt, bfg, bbg = f"{pct:.1f}%", "#57534E", "#E7E5E4"
            elif pct > 0:
                btxt, bfg, bbg = f"▲+{pct:.1f}%", "#166534", "#DCFCE7"
            else:
                btxt, bfg, bbg = f"▼{pct:.1f}%", "#B91C1C", "#FEE2E2"
            ax.annotate(btxt, xy=(hi + 80, i - 0.05),
                        xytext=(55, 0), textcoords="offset points",
                        ha="left", va="center", fontsize=8, color=bfg,
                        bbox={"boxstyle": "round,pad=0.25",
                              "facecolor": bbg, "edgecolor": "none"})

        ax.annotate(label, xy=(0, i), xycoords=("axes fraction", "data"),
                    xytext=(-8, 0), textcoords="offset points",
                    ha="right", va="center", fontsize=10, color=INK)

    ax.set_yticks([])
    style_ax(ax, xlabel=c["xlabel"], grid="")
    ax.grid(False)
    ax.set_ylim(-0.7, n_items + 0.2)
    pad = 250
    ax.set_xlim(df["p25"].min() - pad, df["p75"].max() + pad + 800)
    ax.xaxis.set_major_formatter(
        mticker.FuncFormatter(lambda x, _p: f"{fmt_int(x)}"))

    fig.subplots_adjust(left=0.20, right=0.97, top=0.82, bottom=0.16)
    fig.text(0.01, 0.98, c["title"], fontsize=18, color=INK,
             fontweight="bold", va="top")
    fig.text(0.01, 0.91, c["subtitle"], fontsize=12, color=MUTED,
             va="top", style="italic")
    fig.text(0.97, 0.98, "2024", fontsize=12, color=MUTED,
             ha="right", va="top")
    fig.text(0.97, 0.93, "YoY vs 2023", fontsize=10, color=MUTED,
             ha="right", va="top")
    fig.text(0.01, 0.04, c["note"], fontsize=10, color=MUTED, va="top")
    return fig


