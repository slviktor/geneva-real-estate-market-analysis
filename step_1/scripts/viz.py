def fig_quarterly_corridor(price: pd.DataFrame, copy: dict) -> plt.Figure:
    """Two-panel quarterly chart: apartments + houses with P25-P75 band."""
    c = ch(copy, "21_quarterly_corridor")
    q = price[
        (price.source == "T_05_05_1_1_02")
        & (price.geo_id == "0000")
        & (price["median"].notna())
    ].copy()
    q["t"] = q.year + (q.quarter - 1) / 4

    apt = q[q.type_id == "ppe_existing"].sort_values("t")
    hou = q[q.type_id == "house_existing"].sort_values("t")

    fig, (ax1, ax2) = plt.subplots(2, 1, figsize=(10.2, 8.0), sharex=True)

    for ax, df, color, band_c, ylabel in [
        (ax1, apt, PPE, BAND, c["ylabel_apt"]),
        (ax2, hou, HOUSE, "#FED7AA", c["ylabel_house"]),
    ]:
        med_m = df["median"] / 1e6
        p25_m = df.p25 / 1e6
        p75_m = df.p75 / 1e6
        ax.fill_between(df.t, p25_m, p75_m, color=band_c, linewidth=0, alpha=0.7)
        ax.plot(df.t, med_m, color=color, linewidth=2.0)
        style_ax(ax, ylabel)
        ax.tick_params(labelsize=10)

        peak = med_m.cummax()
        drawdown = (med_m.values - peak.values) / peak.values * 100
        max_dd = drawdown.min()
        dd_idx = int(drawdown.argmin())
        dd_t = df.t.iloc[dd_idx]
        dd_val = med_m.iloc[dd_idx]

        ax.annotate(
            f"max drawdown {max_dd:.0f}%",
            xy=(dd_t, dd_val), xytext=(15, -20),
            textcoords="offset points", fontsize=9, color="#B91C1C",
            arrowprops={"arrowstyle": "->", "color": "#B91C1C", "lw": 1},
            bbox={"boxstyle": "round,pad=0.3", "facecolor": "#FEE2E2",
                  "edgecolor": "none"},
        )

    ax2.set_xlabel("")
    years = sorted(set(int(y) for y in q.t if y == int(y)))
    ax2.set_xticks([y for y in years if y % 2 == 0])
    ax2.set_xticklabels([str(y) for y in years if y % 2 == 0])

    fig.subplots_adjust(left=0.10, right=0.97, top=0.86, bottom=0.10,
                        hspace=0.18)
    fig.text(0.01, 0.98, c["title"], fontsize=17, color=INK,
             fontweight="bold", va="top")
    fig.text(0.01, 0.03, c["note"], fontsize=10, color=MUTED, va="top")
    return fig


