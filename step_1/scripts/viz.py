def _rings(geom) -> list:
    t = geom.get("type")
    if t == "Polygon":
        return [geom["coordinates"]]
    if t == "MultiPolygon":
        return list(geom["coordinates"])
    return []


def _patch(ring) -> PathPatch | None:
    exterior = ring[0]
    verts = [(float(x), float(y)) for x, y, *_ in exterior]
    if len(verts) < 3:
        return None
    codes = [MPath.MOVETO] + [MPath.LINETO] * (len(verts) - 1)
    return PathPatch(MPath(verts, codes))


def fig_ppe_map(gj: dict, price: pd.DataFrame, copy: dict) -> plt.Figure:
    vals = ppe_m2(price, geo=None, communes_only=True)
    vals = vals[vals.year == 2024][["geo_id", "geo_label", "median", "n"]]
    lookup = dict(zip(vals["geo_id"].astype(str), vals["median"].astype(float)))
    cmap = plt.cm.Blues
    vmin, vmax = min(lookup.values()), max(lookup.values())
    norm = Normalize(vmin=vmin, vmax=vmax)
    colored, grey = [], []
    for ft in gj["features"]:
        props = ft["properties"]
        name = str(props.get("commune") or "")
        bfs = props.get("no_com_federal")
        gid = "6621" if name.startswith("Genève-") else (f"{int(bfs):04d}" if bfs is not None else None)
        med = lookup.get(gid) if gid else None
        for poly in _rings(ft["geometry"]):
            patch = _patch(poly)
            if patch is None:
                continue
            if med is None:
                grey.append(patch)
            else:
                patch.set_facecolor(cmap(norm(med)))
                colored.append(patch)
    fig, ax = plt.subplots(figsize=(8.8, 8.2))
    ax.add_collection(PatchCollection(grey, facecolor=MISS, edgecolor="white", linewidths=0.4, match_original=False))
    ax.add_collection(PatchCollection(colored, match_original=True, edgecolor="white", linewidths=0.4))
    ax.set_aspect("equal")
    ax.autoscale()
    ax.axis("off")
    c = ch(copy, "03_ppe_map")
    title(ax, c["title"])
    sm = plt.cm.ScalarMappable(norm=norm, cmap=cmap)
    cb = fig.colorbar(sm, ax=ax, fraction=0.035, pad=0.02, shrink=0.65)
    cb.ax.tick_params(labelsize=8, colors=MUTED)
    cb.set_label(c["ylabel"], fontsize=8, color=MUTED)
    fig.subplots_adjust(left=0.02, right=0.90, top=0.90, bottom=0.12)
    caption(fig, c["note"])
    return fig


def _centroid(geom) -> tuple[float, float]:
    """Average of exterior ring vertices — rough centroid."""
    xs, ys = [], []
    for ring in _rings(geom):
        for x, y, *_ in ring[0]:
            xs.append(float(x))
            ys.append(float(y))
    return (sum(xs) / len(xs), sum(ys) / len(ys)) if xs else (0, 0)


def _load_lake() -> list[list[float]] | None:
    """Load Lac Léman polygon if available."""
    import json as _json
    lake_path = ROOT / "raw" / "lake_leman.geojson"
    if not lake_path.exists():
        return None
    with open(lake_path, encoding="utf-8") as f:
        feat = _json.load(f)
    geom = feat.get("geometry", {})
    if geom.get("type") == "Polygon":
        return geom["coordinates"][0]
    if geom.get("type") == "MultiPolygon":
        return geom["coordinates"][0][0]
    return None


